import {beforeEach,afterEach,describe,it,expect,vi} from 'vitest'
import {mount,flushPromises} from '@vue/test-utils'
import CreateOrderView from '../src/views/CreateOrderView.vue'
import {auth} from '../src/state/auth'
const api=vi.hoisted(()=>({options:vi.fn(),products:vi.fn(),create:vi.fn()}))
vi.mock('../src/api/orders',()=>({orderApi:api}))
vi.mock('vue-router',()=>({useRouter:()=>({replace:vi.fn()})}))
let wrapper:ReturnType<typeof mount>
beforeEach(()=>{vi.clearAllMocks();auth.session.value={account:{id:'member',providerName:'渠道',personName:'人员',mobile:'13800138000',role:'member',enabled:true},expiresAt:Date.now()+100000};api.options.mockResolvedValue({demo:false,cities:[{id:'city',name:'上海'}],brands:[{id:'brand',name:'品牌'}],platforms:[{id:'platform',name:'服务商对应平台'}]});api.products.mockResolvedValue({products:[{id:'catalog',name:'测试洁面',upc:'001234567890',spec:'20ml',price:1234,brandName:'品牌',imageUrl:'https://cdn.example/product.jpg'}],page:1,hasMore:false})})
afterEach(()=>wrapper?.unmount())
describe('商品库选品',()=>{it('按 UPC 搜索后带入商品，参考价保持分到元转换，再次选择增加数量',async()=>{
  wrapper=mount(CreateOrderView,{global:{stubs:{RouterLink:true}}});await flushPromises()
  await wrapper.get('[aria-label="UPC 或商品名称"]').setValue('001234567890')
  await wrapper.get('.product-search-row button').trigger('click');await flushPromises()
  expect(api.products).toHaveBeenCalledWith('001234567890',1)
  await wrapper.get('.product-results button').trigger('click')
  expect((wrapper.get('[aria-label="商品 1 名称"]').element as HTMLInputElement).value).toBe('测试洁面')
  expect((wrapper.get('[aria-label="商品 1 单价"]').element as HTMLInputElement).value).toBe('12.34')
  expect(wrapper.text()).toContain('UPC：001234567890')
  expect((wrapper.get('[aria-label="订单平台"]').element as HTMLSelectElement).value).toBe('platform')
  await wrapper.get('.product-results button').trigger('click');expect((wrapper.get('[aria-label="商品 1 数量"]').element as HTMLInputElement).value).toBe('2')
})})

it('默认浏览远端商品列表，支持下一页，接口失败时不显示本地回退商品',async()=>{
  api.products.mockResolvedValueOnce({products:[],page:1,hasMore:true})
  wrapper=mount(CreateOrderView,{global:{stubs:{RouterLink:true}}});await flushPromises()
  expect(api.products).toHaveBeenCalledWith('',1)
  api.products.mockResolvedValueOnce({products:[],page:2,hasMore:false})
  await wrapper.get('.product-pages button:last-child').trigger('click');await flushPromises()
  expect(api.products).toHaveBeenLastCalledWith('',2)
  api.products.mockRejectedValueOnce(new Error('商品库暂时无法连接，请重试'))
  await wrapper.get('.product-search-row button').trigger('click');await flushPromises()
  expect(wrapper.text()).toContain('商品库暂时无法连接');expect(wrapper.find('.product-results').exists()).toBe(false)
})
it('外部订单号留空可提交，加入商品后的价格及目录快照保持正确',async()=>{
  api.create.mockResolvedValue({id:'created'})
  wrapper=mount(CreateOrderView,{global:{stubs:{RouterLink:true}}});await flushPromises()
  await wrapper.get('[aria-label="城市"]').setValue('city');await wrapper.get('[aria-label="品牌"]').setValue('brand')
  await wrapper.get('.product-results button').trigger('click')
  await wrapper.get('[aria-label="收件信息"]').setValue('收件人和完整地址')
  await wrapper.get('[aria-label="订单应付金额"]').setValue('12.34')
  expect(wrapper.get('.items-table .order-product-thumbnail img').attributes('src')).toBe('https://cdn.example/product.jpg')
  expect((wrapper.get('[aria-label="外部订单号"]').element as HTMLInputElement).value).toBe('')
  await wrapper.get('form').trigger('submit');await flushPromises()
  expect(api.create).toHaveBeenCalledWith(expect.objectContaining({referenceId:'',items:[expect.objectContaining({upc:'001234567890',catalogId:'catalog',salesPrice:1234,imageUrl:'https://cdn.example/product.jpg'})]}),expect.any(String))
})

it('选品按品牌名称匹配履约品牌编号，自动带出后允许手动修改',async()=>{
  api.options.mockResolvedValueOnce({demo:false,cities:[{id:'city',name:'上海'}],brands:[{id:'fulfillment-brand',name:'CPB/肌肤之钥'},{id:'other',name:'其他品牌'}],platforms:[{id:'platform',name:'平台'}]})
  api.products.mockResolvedValueOnce({products:[{id:'catalog',name:'洁面',upc:'001234567890',spec:'20ml',price:1234,brandId:'different-standard-brand-id',brandName:'CPB/肌肤之钥\t',imageUrl:'https://cdn.example/product.jpg'}],page:1,hasMore:false})
  wrapper=mount(CreateOrderView,{global:{stubs:{RouterLink:true}}});await flushPromises()
  expect(wrapper.get('.product-thumbnail img').attributes('src')).toBe('https://cdn.example/product.jpg')
  await wrapper.get('.product-results button').trigger('click')
  expect((wrapper.get('[aria-label="品牌"]').element as HTMLSelectElement).value).toBe('fulfillment-brand')
  await wrapper.get('[aria-label="品牌"]').setValue('other')
  expect((wrapper.get('[aria-label="品牌"]').element as HTMLSelectElement).value).toBe('other')
  expect(wrapper.get('.brand-selection-note').text()).toContain('你的选择')
  await wrapper.get('.product-results button').trigger('click')
  expect((wrapper.get('[aria-label="品牌"]').element as HTMLSelectElement).value).toBe('other')
})
it('商品图片加载失败有占位，未知品牌保留手动选择',async()=>{
  api.products.mockResolvedValueOnce({products:[{id:'catalog',name:'洁面',upc:'001234567890',spec:'20ml',price:1234,brandName:'未匹配品牌',imageUrl:'https://cdn.example/missing.jpg'}],page:1,hasMore:false})
  wrapper=mount(CreateOrderView,{global:{stubs:{RouterLink:true}}});await flushPromises()
  await wrapper.get('.product-thumbnail img').trigger('error')
  expect(wrapper.find('.product-thumbnail img').exists()).toBe(false);expect(wrapper.get('.product-thumbnail').text()).toBe('暂无图')
  await wrapper.get('.product-results button').trigger('click')
  expect((wrapper.get('[aria-label="品牌"]').element as HTMLSelectElement).value).toBe('')
  expect(wrapper.get('.brand-selection-note').text()).toContain('手动确认')
})
